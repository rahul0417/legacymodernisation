def get_seed(n: int, salt: str, padding: int) -> str:
    """Compute the decimal seed string padded to `padding` chars.

    Algorithm (LOCKED — Invariants I-4, I-9):
        1. h = md5_hex(str(n) + salt)      # NOT salt + str(n)
        2. dec = int(h[0:padding], 16)
        3. num = dec mod (10 ** padding)
        4. if num == 0: num = 1            # zero-guard
        5. return ljust(num, padding, '0')  # right-pad — PHP `str_pad` default is STR_PAD_RIGHT

    NB: PHP `str_pad($num, $padding, '0')` (no 4th arg) right-pads with '0'.
    Comprehension §4.1's wording "left-pad" was an error against the legacy.
    We follow the legacy: `"7"` with padding=3 becomes `"700"`, not `"007"`.
    """
    h = _md5_hex(str(n) + salt)
    dec = int(h[0:padding], 16)
    # Invariant I-7 also applies here: 10 ** padding stays integer.
    num = dec % (10 ** padding)
    if num == 0:
        num = 1
    return str(num).ljust(padding, "0")


def num_to_alpha(n: int, chars: str) -> str:
    """Bijective base-len(chars) encoding of a non-negative integer.

    Uses integer-only arithmetic (// not /). See Invariant I-6.
    """
    b = len(chars)
    m = n % b

    # Single-character output when n < b.
    if n - m == 0:
        return chars[n]

    a = ""
    while m > 0 or n > 0:
        a = chars[m] + a
        n = (n - m) // b  # Invariant I-6: integer division only
        m = n % b

    return a


def alpha_to_num(code: str, chars: str) -> int:
    """Inverse of num_to_alpha. Raises ValueError on invalid char.

    Uses exact integer exponentiation `b ** e` (Invariant I-7) — never
    float pow().
    """
    b = len(chars)
    L = len(code)
    n = 0
    for i in range(L):
        ch = code[i]
        idx = chars.find(ch)
        if idx < 0:
            raise ValueError(
                f"alpha_to_num: character {ch!r} not in chars alphabet"
            )
        n += idx * (b ** (L - i - 1))
    return n


def _md5_hex(material: str) -> str:
    """Return lowercase 32-char hex MD5 digest."""
    return hashlib.md5(material.encode("utf-8")).hexdigest()


def _validate_chars(chars: str) -> None:
    """Raise ValueError if chars has duplicates or len < 2."""
    if len(chars) < 2:
        raise ValueError(
            f"chars must contain at least 2 characters, got {len(chars)}"
        )
    if len(set(chars)) != len(chars):
        raise ValueError("chars must contain unique characters (no duplicates)")
